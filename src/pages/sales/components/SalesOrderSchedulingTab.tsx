import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { Pencil } from 'lucide-react';
import { toast } from 'sonner';
import { Badge, Spinner } from '@/components/tenant/ui';
import { apiErrorMessage } from '@/api/tenantClient';
import { cn } from '@/lib/utils';
import { formatDisplayDate } from '@/lib/dateUtils';
import { salesOrderService } from '@/services/salesOrderService';
import { PLANNER_QUERY_KEY } from '@/lib/plannerCalendar';
import {
  SCHEDULE_STATUS_COLORS,
  SCHEDULE_STATUS_LABELS,
  displayStatus,
  formatWallClock,
  scheduleProgress,
} from '@/lib/salesOrderSchedule';
import type { SalesOrderScheduleActivityPatch } from '@/types/salesOrder';
import { SalesOrderScheduleRowEditor } from './SalesOrderScheduleRowEditor';

const HEADERS = ['Activity', 'Status', 'Scheduled', 'Completed on', 'Notes'];
const ACTION_COLUMN_LABEL = 'Edit';

function savedMessage(name: string, patch: SalesOrderScheduleActivityPatch): string {
  if (patch.status === 'completed') return `${name} marked completed.`;
  if (patch.status === 'scheduled') return `${name} moved back to scheduled.`;
  return `${name} updated.`;
}

/** The order's auto-planned production schedule: one row per activity with its
 *  status, scheduled and completed times, and notes. The plan is generated by
 *  the server when the scheduled installation date is saved; a planner (anyone
 *  who can edit the order) then ticks rows off, nudges dates, and adds notes. */
export function SalesOrderSchedulingTab({ orderId, installDate, canEdit }: {
  orderId: string;
  /** The order's scheduled installation date (`yyyy-mm-dd`), when it has one. */
  installDate?: string;
  canEdit: boolean;
}) {
  const navigate = useNavigate();
  const queryClient = useQueryClient();
  const [editingCode, setEditingCode] = useState<string | null>(null);
  const queryKey = ['sales-order-schedule', orderId];

  const { data: activities = [], isLoading, error } = useQuery({
    queryKey,
    queryFn: () => salesOrderService.getSchedule(orderId),
  });

  const save = useMutation({
    mutationFn: ({ code, patch }: { code: string; patch: SalesOrderScheduleActivityPatch }) =>
      salesOrderService.updateScheduleActivity(orderId, code, patch),
    onSuccess: (updated, { patch }) => {
      queryClient.invalidateQueries({ queryKey });
      // The Activity Planner lists these same rows across every order.
      queryClient.invalidateQueries({ queryKey: [PLANNER_QUERY_KEY] });
      setEditingCode(null);
      toast.success(savedMessage(updated.name, patch));
    },
  });

  function startEditing(code: string) {
    save.reset();
    setEditingCode(code);
  }

  if (isLoading) return <div className="py-8 flex justify-center"><Spinner label="Loading schedule…" /></div>;
  if (error) {
    return <p role="alert" className="py-8 text-center text-xs text-destructive/70">{apiErrorMessage(error, 'Failed to load the schedule.')}</p>;
  }

  if (activities.length === 0) {
    return (
      <div className="space-y-3 rounded-lg border border-dashed border-stone-300 bg-white py-10 text-center">
        <p className="text-sm font-semibold text-stone-700">No schedule yet</p>
        <p className="mx-auto max-w-md text-xs text-stone-500">
          The production schedule is planned from the order&apos;s Scheduled Installation Date. Set one on the order
          and the activities appear here.
        </p>
        {canEdit && (
          <button
            type="button"
            onClick={() => navigate(`/sales/sales_order/${orderId}/edit`)}
            className="inline-flex items-center gap-1.5 rounded-lg border border-stone-300 bg-white px-3 py-1.5 text-xs font-semibold text-stone-700 shadow-sm transition-colors hover:bg-stone-50"
          >
            <Pencil className="size-3.5" aria-hidden="true" />
            Set installation date
          </button>
        )}
      </div>
    );
  }

  const now = new Date();
  const progress = scheduleProgress(activities, now);

  return (
    <div className="space-y-3">
      <div className="flex flex-wrap items-center gap-x-5 gap-y-1 text-xs text-stone-600">
        {installDate && (
          <span>
            Installation: <span className="font-semibold text-stone-900">{formatDisplayDate(installDate)}</span>
          </span>
        )}
        <span>
          <span className="font-semibold text-stone-900">{progress.completed}</span> of {progress.total} completed
        </span>
        {progress.overdue > 0 && (
          <span className="font-semibold text-destructive">{progress.overdue} overdue</span>
        )}
      </div>

      <div className="overflow-x-auto modal-scrollbar rounded-lg border border-stone-200 bg-white">
        <table className="w-full text-left text-xs">
          <thead className="bg-stone-50 border-b border-stone-200">
            <tr>
              {HEADERS.map((h) => (
                <th key={h} scope="col" className="px-3 py-2.5 text-2xs font-semibold uppercase tracking-wide text-stone-500 whitespace-nowrap">{h}</th>
              ))}
              {canEdit && (
                <th scope="col" className="w-10 px-3 py-2.5"><span className="sr-only">{ACTION_COLUMN_LABEL}</span></th>
              )}
            </tr>
          </thead>
          <tbody className="divide-y divide-stone-100">
            {activities.map((a, i) => {
              const status = displayStatus(a, now);
              const startsPhase = i > 0 && activities[i - 1].group !== a.group;
              if (canEdit && editingCode === a.code) {
                return (
                  <tr key={a.code} className={cn(startsPhase && 'border-t-2 border-t-stone-200')}>
                    <td colSpan={HEADERS.length + 1} className="p-0">
                      <div className="border-l-2 border-l-brand">
                        <p className="px-3 pt-3 text-xs font-semibold text-stone-900">{a.name}</p>
                        <SalesOrderScheduleRowEditor
                          activity={a}
                          saving={save.isPending}
                          error={save.isError ? apiErrorMessage(save.error, 'Failed to update the activity.') : undefined}
                          onSave={(patch) => save.mutate({ code: a.code, patch })}
                          onCancel={() => setEditingCode(null)}
                        />
                      </div>
                    </td>
                  </tr>
                );
              }
              return (
                <tr
                  key={a.code}
                  className={cn('hover:bg-stone-50/50', startsPhase && 'border-t-2 border-t-stone-200')}
                >
                  <td className="px-3 py-2.5 font-medium text-stone-800 whitespace-nowrap">{a.name}</td>
                  <td className="px-3 py-2.5">
                    <Badge color={SCHEDULE_STATUS_COLORS[status]} size="sm">{SCHEDULE_STATUS_LABELS[status]}</Badge>
                  </td>
                  <td className={cn('px-3 py-2.5 tabular-nums whitespace-nowrap', status === 'overdue' ? 'text-destructive' : 'text-stone-600')}>
                    {formatWallClock(a.scheduledAt) || '—'}
                  </td>
                  <td className="px-3 py-2.5 tabular-nums whitespace-nowrap text-stone-600">
                    {formatWallClock(a.completedAt) || <span className="text-stone-300">—</span>}
                  </td>
                  <td className="max-w-xs px-3 py-2.5 text-stone-600">
                    {a.notes ? <span className="block truncate" title={a.notes}>{a.notes}</span> : <span className="text-stone-300">—</span>}
                  </td>
                  {canEdit && (
                    <td className="px-3 py-2.5 text-right">
                      <button
                        type="button"
                        onClick={() => startEditing(a.code)}
                        className="rounded-md p-1.5 text-stone-400 transition-colors hover:bg-stone-100 hover:text-stone-700"
                        aria-label={`Edit ${a.name}`}
                      >
                        <Pencil className="size-3.5" aria-hidden="true" />
                      </button>
                    </td>
                  )}
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>

      <p className="text-2xs text-stone-400">
        Dates were planned from the installation date. Changing that date re-plans every activity that isn&apos;t completed yet.
      </p>
    </div>
  );
}
